#requires -Version 7
<#
  Renames the two legacy product names to FigIran across both repos (parent + the upstream-derived submodule),
  removes licence/notice files, and verifies. Idempotent; re-run it after every upstream merge. See README.txt.
  Usage: pwsh figiran-tools\rebrand\rebrand.ps1 [-WhatIf] [-SkipCargo] [-SkipZip] [-AppOnly -Root <app repo or worktree>]
  Exit code: 0 = clean (only allowlisted residuals), 1 = something is left.
  The legacy names are assembled from pieces on purpose, so that this file itself is not a trace.
#>
[CmdletBinding()]
param(
  [switch]$WhatIf,
  [switch]$SkipCargo,
  [switch]$SkipZip,
  [switch]$VerifyOnly,   # skip every change, run only the verification scan
  [switch]$AppOnly,   # -Root is the upstream-derived app repo itself (no parent repo, no submodule rename)
  [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path,
  [string]$SubmoduleName = ('fig' + 'craft')
)
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8
$utf8Strict = [Text.UTF8Encoding]::new($false, $true)
$utf8 = [Text.UTF8Encoding]::new($false)

# ---- legacy names, assembled ------------------------------------------------------------------
$F = 'fi' + 'g'; $A = 'ar' + 't'; $C = 'cra' + 'ft'
$nameRx = "(?:$F|$A)[-_ ]?$C"
$faRx = '(?:ف[یي]گ|آرت)[‌ ]?[کك]را?فت'
$replaceRx = [regex]::new("(?i)ai\.storyteller\.$nameRx|$nameRx|$faRx")
$findRx = "(?i)$nameRx|$faRx"
$findRxNet = [regex]::new($findRx)
$faNew = "`u{0641}`u{06CC}`u{06AF}`u{200C}`u{0627}`u{06CC}`u{0631}`u{0627}`u{0646}"
$licenseRx = [regex]::new('(?i)(^|/)(LICEN[SC]E|COPYING|NOTICE|UNLICENSE)([._-][^/]*)?$|(^|/)[^/]*-LICENSE[^/]*$')

function Convert-Name([string]$v) {
  if ($v -imatch '^ai\.storyteller\.') { return 'ai.figiran.app' }
  if ($v[0] -gt [char]0x0600) { return $faNew }
  $first = $v[0]; $craftFirst = $v[$v.Length - 5]
  if ($v -ceq $v.ToUpperInvariant()) { return 'FIGIRAN' }
  if ([char]::IsUpper($first)) {
    if ($v.Contains(' ')) { return 'Fig Iran' }
    if ([char]::IsUpper($craftFirst)) { return 'FigIran' }
    return 'Figiran'
  }
  if ([char]::IsUpper($craftFirst)) { return 'figIran' }
  return 'figiran'
}
$evaluator = [Text.RegularExpressions.MatchEvaluator] { param($m) Convert-Name $m.Value }
function Convert-Text([string]$s) { $replaceRx.Replace($s, $evaluator) }

# ---- allowlist of documented residuals: a line (not a file) that must keep a real address ----------
$Allow = @(
  @{ Repo = 'parent'; Path = '^\.gitmodules$'; Line = '^\s*(url|path)\s*=|^\[submodule';
     Why = 'the submodule folder keeps the upstream creator name (figcraft), like its real GitHub repository' }
)
# binary residuals that cannot be rewritten by bytes (DER certificates embed the name inside signed data): they are regenerated by hand in dev;
# the mirror keeps the upstream bytes, so a hand-made version in dev wins the merge and only an upstream change to them needs a human.
$BinAllow = [regex]::new('(^|/)crates/collab-net/src/testdata/[^/]+\.der$')
function Test-Allowed([string]$repoKey, [string]$path, [string]$line) {
  foreach ($a in $Allow) { if ($a.Repo -eq $repoKey -and $path -match $a.Path -and $line -match $a.Line) { return $true } }
  $false
}
function Get-AllowForFile([string]$repoKey, [string]$path) { $Allow | ? { $_.Repo -eq $repoKey -and $path -match $_.Path } }

$stats = [ordered]@{ FilesRewritten = 0; Occurrences = 0; FilesRenamed = 0; DirsRenamed = 0; ZipsRewritten = 0; LicensesRemoved = 0 }
function Note([string]$m) { Write-Host $m }

function Get-Paths([string]$repo) {   # tracked + untracked-not-ignored, existing only (relative, '/')
  $raw = & git -C $repo -c core.quotepath=off ls-files -z -c -o --exclude-standard
  ($raw -split "`0") | ? { $_ } | Sort-Object -Unique | ? { Test-Path -LiteralPath (Join-Path $repo $_) }
}
function Read-TextFile([string]$p) {
  $b = [IO.File]::ReadAllBytes($p)
  if ($b.Length -gt 30MB) { return $null }
  $n = [Math]::Min($b.Length, 8192)
  if ([Array]::IndexOf($b, [byte]0, 0, $n) -ge 0) { return $null }
  $bom = $b.Length -ge 3 -and $b[0] -eq 0xEF -and $b[1] -eq 0xBB -and $b[2] -eq 0xBF
  $off = if ($bom) { 3 } else { 0 }
  try { $s = $utf8Strict.GetString($b, $off, $b.Length - $off) } catch { return $null }
  [pscustomobject]@{ Text = $s; Bom = $bom }
}

# ---- step: remove licence / notice files (project's own tree only) ---------------------------------
function Remove-Licenses([string]$repo, [string[]]$paths) {
  foreach ($rel in $paths | ? { $licenseRx.IsMatch($_) }) {
    $full = Join-Path $repo $rel
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { continue }
    $stats.LicensesRemoved++
    if ($WhatIf) { Note "  delete $rel"; continue }
    & git -C $repo rm -q -f --ignore-unmatch -- $rel 2>$null
    if (Test-Path -LiteralPath $full) { Remove-Item -LiteralPath $full -Force }
  }
}

# ---- step: rewrite contents ---------------------------------------------------------------------
function Rewrite-Contents([string]$repo, [string]$repoKey, [string[]]$paths) {
  foreach ($rel in $paths) {
    if ($rel -like 'figiran-tools/rebrand/*') { continue }
    $full = Join-Path $repo $rel
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { continue }
    $t = Read-TextFile $full
    if ($null -eq $t -or -not $findRxNet.IsMatch($t.Text)) { continue }
    $allowFile = Get-AllowForFile $repoKey $rel
    if ($allowFile) {
      $new = ([regex]::Split($t.Text, '(?<=\n)') | % { $l = $_; if ($allowFile | ? { $l -match $_.Line }) { $l } else { Convert-Text $l } }) -join ''
    } else { $new = Convert-Text $t.Text }
    if ($new -ceq $t.Text) { continue }
    $stats.FilesRewritten++; $stats.Occurrences += $findRxNet.Matches($t.Text).Count
    if (-not $WhatIf) {
      $bytes = $utf8.GetBytes($new)
      if ($t.Bom) { $bytes = [byte[]](0xEF, 0xBB, 0xBF) + $bytes }
      [IO.File]::WriteAllBytes($full, $bytes)
    }
  }
}

# ---- step: product-extension files are zip archives with a JSON format marker; rewrite text entries ---
function Rewrite-Zips([string]$repo, [string[]]$paths) {
  Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
  foreach ($rel in $paths | ? { $_ -match "(?i)\.(${F}craft|${F}iran)$" }) {
    $full = Join-Path $repo $rel
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { continue }
    $head = [IO.File]::ReadAllBytes($full)[0..1]
    if ($head[0] -ne 0x50 -or $head[1] -ne 0x4B) { continue }
    $zin = [IO.Compression.ZipFile]::OpenRead($full)
    $items = foreach ($e in $zin.Entries) {
      $ms = [IO.MemoryStream]::new(); $s = $e.Open(); $s.CopyTo($ms); $s.Dispose()
      $b = $ms.ToArray(); $changed = $false
      if ($e.FullName -imatch '\.(json|txt|md|xml|svg)$' -and [Array]::IndexOf($b, [byte]0) -lt 0) {
        $txt = $utf8.GetString($b)
        if ($findRxNet.IsMatch($txt)) { $b = $utf8.GetBytes((Convert-Text $txt)); $changed = $true }
      }
      [pscustomobject]@{ Name = $e.FullName; Bytes = $b; Time = $e.LastWriteTime; Changed = $changed }
    }
    $zin.Dispose()
    if (-not ($items | ? Changed)) { continue }
    $stats.ZipsRewritten++
    if ($WhatIf) { continue }
    $tmp = "$full.rebrand.tmp"; if (Test-Path $tmp) { Remove-Item $tmp -Force }
    $zout = [IO.Compression.ZipFile]::Open($tmp, 'Create')
    foreach ($i in $items) {
      $ne = $zout.CreateEntry($i.Name, [IO.Compression.CompressionLevel]::Optimal); $ne.LastWriteTime = $i.Time
      $os = $ne.Open(); $os.Write($i.Bytes, 0, $i.Bytes.Length); $os.Dispose()
    }
    $zout.Dispose()
    Move-Item -LiteralPath $tmp -Destination $full -Force
  }
}

# ---- step: rename files and directories (deepest first; git mv when tracked, plain move otherwise) -----
function Rename-Paths([string]$repo, [string[]]$paths) {
  $targets = [Collections.Generic.HashSet[string]]::new()
  foreach ($p in $paths) {
    $segs = $p.Split('/')
    for ($i = 0; $i -lt $segs.Length; $i++) {
      if ($findRxNet.IsMatch($segs[$i])) { [void]$targets.Add(($segs[0..$i] -join '/')) }
    }
  }
  foreach ($old in $targets | Sort-Object { ($_ -split '/').Count } -Descending) {
    $segs = $old.Split('/'); $leafNew = Convert-Text $segs[-1]
    $newRel = (@($segs[0..($segs.Length - 2)] | ? { $_ -and $segs.Length -gt 1 }) + $leafNew) -join '/'
    $oldFull = Join-Path $repo $old; $newFull = Join-Path $repo $newRel
    if (-not (Test-Path -LiteralPath $oldFull)) { continue }
    if (Test-Path -LiteralPath $oldFull -PathType Container) { $stats.DirsRenamed++ } else { $stats.FilesRenamed++ }
    if ($WhatIf) { Note "  rename $old -> $leafNew"; continue }
    if (Test-Path -LiteralPath $newFull) { Note "  SKIPPED (target exists, a locked leftover of an earlier run?): $old"; continue }
    & git -C $repo mv -- $old $newRel 2>$null
    if ($LASTEXITCODE -ne 0) {
      try { Move-Item -LiteralPath $oldFull -Destination $newFull -ErrorAction Stop }
      catch {   # something (e.g. an open Visual Studio) locks a child: move the rest, leave the locked child behind
        New-Item -ItemType Directory -Path $newFull -Force | Out-Null
        foreach ($c in Get-ChildItem -LiteralPath $oldFull -Force) {
          try { Move-Item -LiteralPath $c.FullName -Destination $newFull -ErrorAction Stop } catch { Note "  LOCKED, left behind: $old/$($c.Name) (close the program using it and delete it)" }
        }
      }
      if ((& git -C $repo ls-files -s -- $old) -match '^160000') { & git -C $repo rm -q --cached -- $old 2>$null; & git -C $repo add -- $newRel 2>$null }
    }
  }
}

# ---- step: git internals of a renamed submodule (module dir, gitdir pointer, config section) ----------
function Rename-SubmoduleInternals([string]$parent, [string]$oldName, [string]$newName) {
  $oldDir = Join-Path $parent ".git\modules\$oldName"; $newDir = Join-Path $parent ".git\modules\$newName"
  if (-not (Test-Path $oldDir) -or (Test-Path $newDir)) { return }
  Move-Item $oldDir $newDir
  [IO.File]::WriteAllText((Join-Path $parent "$newName\.git"), "gitdir: ../.git/modules/$newName`n")
  & git -C $parent config --rename-section "submodule.$oldName" "submodule.$newName" 2>$null
  & git -C $newDir config core.worktree "../../../$newName"
}

# ============================================ main ==================================================
$sub = Join-Path $Root $SubmoduleName
if (-not (Test-Path (Join-Path $sub '.git'))) { $sub = Join-Path $Root $SubmoduleName }
$repos = @()
if ($AppOnly) { $repos += @{ Key = 'sub'; Path = $Root } }
else {
  if (Test-Path (Join-Path $sub '.git')) { $repos += @{ Key = 'sub'; Path = $sub } }
  $repos += @{ Key = 'parent'; Path = $Root }
}

Note "Root: $Root   WhatIf: $WhatIf"
foreach ($r in $repos) {
  if ($VerifyOnly) { break }
  Note "== $($r.Key): $($r.Path)"
  $paths = Get-Paths $r.Path
  if ($r.Key -eq 'parent') { $paths = $paths | ? { $_ -ne $SubmoduleName -and $_ -ne '.gitmodules' } }   # the submodule folder keeps its name
  Remove-Licenses $r.Path $paths
  $paths = $paths | ? { -not $licenseRx.IsMatch($_) } | ? { Test-Path -LiteralPath (Join-Path $r.Path $_) }
  Rewrite-Contents $r.Path $r.Key $paths
  if (-not $SkipZip) { Rewrite-Zips $r.Path $paths }
  if ($r.Key -eq 'parent') {   # ignored local note files at the root follow the product name too
    $extra = Get-ChildItem $Root -File -Force | ? { $findRxNet.IsMatch($_.Name) -and $paths -notcontains $_.Name } | % Name
    foreach ($n in $extra) { Rewrite-Contents $Root 'parent' @($n); $paths += $n }
  }
  Rename-Paths $r.Path $paths
}
Note ('Rewritten files: {0}, occurrences: {1}, renamed files: {2}, renamed dirs: {3}, zips: {4}, licence files removed: {5}' -f $stats.FilesRewritten, $stats.Occurrences, $stats.FilesRenamed, $stats.DirsRenamed, $stats.ZipsRewritten, $stats.LicensesRemoved)

# Cargo.lock: textual rename above, then cargo re-sorts and validates it (workspace members only)
if (-not $WhatIf -and -not $VerifyOnly -and -not $SkipCargo -and (Get-Command cargo -ErrorAction SilentlyContinue)) {
  $subNow = if ($AppOnly) { $Root } else { Join-Path $Root $SubmoduleName }
  if (Test-Path (Join-Path $subNow 'Cargo.lock')) {
    Note "cargo update --workspace --offline in $subNow"
    Push-Location $subNow; & cargo update --workspace --offline 2>&1 | Select-Object -Last 3; Pop-Location
  }
}

# ============================================ verification ==========================================
if ($WhatIf) { Note 'WhatIf: verification skipped.'; exit 0 }
$bad = 0
$byteRx = [regex]::new("(?i)$nameRx")
$u16Rx = [regex]::new('(?is)(?:f\0i\0g\0|a\0r\0t\0)(?:[-_ ]\0)?c\0r\0a\0f\0t\0')
$repos = @()
$subNow = if ($AppOnly) { $Root } else { Join-Path $Root $SubmoduleName }
if (Test-Path (Join-Path $subNow '.git')) { $repos += @{ Key = 'sub'; Path = $subNow } }
if (-not $AppOnly) { $repos += @{ Key = 'parent'; Path = $Root } }
foreach ($r in $repos) {
  $k = $r.Key; $p = $r.Path
  $hits = & git -C $p -c core.quotepath=off grep -I -i -n -E --untracked $findRx 2>$null
  $left = @($hits | ? { $_ } | ? {
      $m = [regex]::Match($_, '^(?<f>[^:]+):(?<n>\d+):(?<l>.*)$')
      -not ($m.Success -and (Test-Allowed $k $m.Groups['f'].Value $m.Groups['l'].Value)) -and $_ -notlike 'figiran-tools/rebrand/*' })
  Note "[$k] text occurrences left: $($left.Count)"; $left | Select-Object -First 15 | % { Note ('   ' + $_.Substring(0, [Math]::Min(160, $_.Length))) }
  $bad += $left.Count
  $names = @(Get-Paths $p | ? { $_ -ne $SubmoduleName } | ? { $findRxNet.IsMatch($_) -or $licenseRx.IsMatch($_) })
  Note "[$k] file/dir names (or licence files) left: $($names.Count)"; $names | Select-Object -First 10 | % { Note "   $_" }
  $bad += $names.Count
  $binHits = 0
  foreach ($rel in (& git -C $p -c core.quotepath=off ls-files -z) -split "`0" | ? { $_ }) {
    $full = Join-Path $p $rel
    if (-not (Test-Path -LiteralPath $full -PathType Leaf) -or $rel -like 'figiran-tools/rebrand/*') { continue }
    if ($null -ne (Read-TextFile $full)) { continue }
    if ($BinAllow.IsMatch($rel)) { $b0 = [IO.File]::ReadAllBytes($full); if ($byteRx.IsMatch([Text.Encoding]::Latin1.GetString($b0))) { Note "   binary (allowlisted, regenerate by hand): $rel" }; continue }
    $b = [IO.File]::ReadAllBytes($full); $s = [Text.Encoding]::Latin1.GetString($b)
    $n = $byteRx.Matches($s).Count + $u16Rx.Matches($s).Count
    if ($b.Length -gt 3 -and $b[0] -eq 0x50 -and $b[1] -eq 0x4B) {
      try {
        $z = [IO.Compression.ZipFile]::OpenRead($full)
        foreach ($e in $z.Entries) { if ($e.Length -lt 50MB) {
            $ms = [IO.MemoryStream]::new(); $st = $e.Open(); $st.CopyTo($ms); $st.Dispose()
            $n += $byteRx.Matches([Text.Encoding]::Latin1.GetString($ms.ToArray())).Count } }
        $z.Dispose()
      } catch { }
    }
    if ($n) { $binHits++; Note "   binary: $rel ($n)" }
  }
  Note "[$k] tracked binaries with the legacy bytes: $binHits"
  $bad += $binHits
}
# informational: ignored/local items (never rewritten; build outputs and runtime data excluded)
$skipDirs = 'bin|obj|target|node_modules|\.next|dist|release|\.vs|\.git|logs|run|dl'
$ign = & git -C $Root status --ignored --porcelain | ? { $_ -like '!! *' } | % { $_.Substring(3).TrimEnd('/') } | ? { $_ -notmatch "(^|/)($skipDirs)$" }
$info = foreach ($i in $ign) {
  $full = Join-Path $Root $i
  $files = if (Test-Path $full -PathType Container) { Get-ChildItem $full -Recurse -File -Force -ErrorAction SilentlyContinue | ? { $_.FullName -notmatch "[\\/]($skipDirs)[\\/]" -and $_.Length -lt 2MB } } else { Get-Item $full }
  foreach ($f in $files) { $t = Read-TextFile $f.FullName; if ($t -and $findRxNet.IsMatch($t.Text)) { $f.FullName.Substring($Root.Length + 1) } }
}
Note "[info] ignored/local files that still mention a legacy name (not tracked, not changed): $(@($info).Count)"; $info | Select-Object -First 15 | % { Note "   $_" }
Note ('Allowlisted residuals: ' + (($Allow | % { "$($_.Repo):$($_.Path) [$($_.Why)]" }) -join '; '))
if ($bad -gt 0) { Note "RESULT: $bad residual(s) -> exit 1"; exit 1 }
Note 'RESULT: clean'; exit 0
